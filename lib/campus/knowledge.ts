export function searchCampusKnowledge(text: string): CampusArticle[] {
  const scored = campusArticles
    .map((article) => {
      const score = article.keywords.reduce(
        (total, keyword) => (text.includes(keyword) ? total + keyword.length : total),
        0
      );
      return { article, score };
    })
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score);

  return scored.slice(0, 2).map((item) => item.article);
}
